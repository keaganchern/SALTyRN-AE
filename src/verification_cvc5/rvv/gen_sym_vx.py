"""Generate rvv/ops/sym_vx_gen.hpp: a symbolic-scalar overload for every concrete
RVV .vx/.vf/.vxm/.wx model that has a .vv counterpart (and vmv.v.x / vfmv.v.f)."""
import re, sys
from pathlib import Path
OPS = Path(sys.argv[1])
SCALARS = {"int8_t", "uint8_t", "int16_t", "uint16_t", "int32_t", "uint32_t", "int64_t", "uint64_t", "float"}
DEF = re.compile(r"inline\s+([\w:]+)\s+(__riscv_\w+)\s*\(([^)]*)\)\s*\{", re.S)
defs, sym_names = {}, set()
for f in sorted(OPS.glob("*.hpp")):
    if f.name == "sym_vx_gen.hpp":
        continue
    for m in DEF.finditer(f.read_text()):
        ret, name, params = m.group(1), m.group(2), " ".join(m.group(3).split())
        ps = [p.strip() for p in params.split(",")] if params.strip() else []
        if "SymbolicScalar" in params:
            sym_names.add(name)
            continue
        defs.setdefault(name, (ret, ps))
def split(p):
    m = re.match(r"(.*?[\s&*])(\w+)$", p)
    return (m.group(1).strip(), m.group(2)) if m else (p, "")
VV = [("_vxm_", "_vvm_"), ("_vfm_", "_vvm_"), ("_vx_", "_vv_"), ("_vf_", "_vv_"), ("_wx_", "_wv_"), ("_wf_", "_wv_")]
out, n = [], 0
for name, (ret, ps) in sorted(defs.items()):
    typed = [split(p) for p in ps]
    if any(not nm for _, nm in typed):
        continue
    sc = [i for i, (t, _) in enumerate(typed) if t in SCALARS]
    # A size_t scalar is a shift amount or index: splat it unsigned at the
    # destination element width (only its low bits are used, as by the .vv form).
    sz = [i for i, (t, nm) in enumerate(typed) if t == "size_t" and nm != "vl"]
    if not sc and len(sz) == 1 and (w := re.search(r"_[iu](8|16|32|64)m", name)):
        sc = sz
        typed = [(f"uint{w.group(1)}_t", nm) if j == sz[0] else (t, nm) for j, (t, nm) in enumerate(typed)]
        ps = [f"{t} {nm}" for t, nm in typed]
    vls = [i for i, (t, nm) in enumerate(typed) if nm == "vl" and t == "size_t"]
    if len(sc) != 1 or not vls:
        continue
    i = sc[0]; T = typed[i][0]; vl = typed[vls[0]][1]
    plist = ", ".join(f"SymbolicScalar<U> {nm}" if j == i else f"{t} {nm}" for j, (t, nm) in enumerate(typed))
    if re.search(r"_v_[xf]_", name) and len(typed) == 2:          # vmv.v.x / vfmv.v.f: a splat
        body = f"return rvv_sym_splat_as<{T}>({typed[i][1]}, {vl});"
    else:
        vv = next((name.replace(a, b, 1) for a, b in VV if a in name), None)
        if not vv or vv not in defs or len(defs[vv][1]) != len(typed):
            continue
        args = ", ".join(f"rvv_sym_splat_as<{T}>({nm}, {vl})" if j == i else nm for j, (_, nm) in enumerate(typed))
        body = f"return {vv}({args});"
    out.append(f"template<typename U> inline {ret} {name}({plist}) {{ {body} }}")
    n += 1
hdr = """#pragma once
// GENERATED by gen_sym_vx.py: a symbolic-scalar overload for every concrete RVV
// .vx/.vf/.vxm/.wx model with a .vv counterpart, and for vmv.v.x / vfmv.v.f.
// The spec defines op.vx(v, x) as op.vv(v, splat(x)), so each forwards to the
// .vv model with x in every lane. x may be any SymbolicScalar<U>: it is
// converted to the intrinsic's scalar type as C converts a call argument.
// Hand-written overloads for an exact type win over these templates.
#include "../intrinsics.hpp"
// included last by _all.hpp, after every concrete model
namespace salt_cvc5 {
template<typename T, typename U>
inline RVVVector rvv_sym_splat_as(SymbolicScalar<U> x, size_t vl) {
    auto& tm = g_ctx->tm;
    SymbolicScalar<T> v = x.template cast<T>();
    Term e = SymTraits<T>::is_fp ? rvv_store_fp32_as_bv(tm, v.term()) : v.term();
    return RVVVector(tm, SymTraits<T>::bits, std::vector<Term>(vl, e));
}
"""
Path(OPS / "sym_vx_gen.hpp").write_text(hdr + "\n".join(out) + "\n} // namespace salt_cvc5\n")
print(n, "overloads;", len(defs), "concrete models scanned")
